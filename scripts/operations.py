"""Реестр операций контракта как тип.

У python-генератора hey-api нет серверного плагина, который печатал бы
типы обработчиков (см. TODO.md). Пока его нет, тип печатается отсюда:
по документу версии и сгенерированным моделям ответа собирается
`TypedDict`, ключи которого — идентификаторы операций, а значения —
вызываемые с нужным типом ответа. Набор обработчиков, объявленный этим
типом, проверяет `ty`: забытая операция, лишняя и ответ не той модели
видны до запуска.

Параметры обработчиков тип не описывает: у них есть зависимости
фреймворка (сессия, настройки), общей сигнатуры у них нет.

Запуск: `python -m scripts.operations` (входит в `make generate-types`).
"""

from importlib import import_module
from pathlib import Path

from app.contract import VERSIONS, document

ROOT = Path(__file__).resolve().parents[1]
HEADER = "# This file is auto-generated by scripts/operations.py\n"
FIRST = "v1"


def _models(version: str):
    return import_module(f"app.types.handlers.{version}.pydantic_gen")


def _response_type(version: str, operation_id: str) -> str:
    """Тип ответа операции в виде выражения для файла версии."""
    class_name = f"{operation_id[0].upper()}{operation_id[1:]}Response"
    model = getattr(_models(version), class_name)
    root = model.model_fields["root"].annotation
    if root is None or root is type(None):
        # У 204 тела нет, обработчик отдаёт готовый ответ.
        return "Response"

    name = root.__name__
    if version == FIRST:
        return name

    # Схема, не менявшаяся между версиями, остаётся тем же классом:
    # обработчики курсов, уроков и токенов общие, и для проверки типов
    # они обязаны быть одним типом, а не двумя с одинаковым содержимым.
    same = getattr(_models(FIRST), name, None)
    if (
        same is not None
        and same.model_json_schema() == root.model_json_schema()
    ):
        return f"{FIRST}.{name}"
    return name


def render(version: str) -> str:
    operations = sorted(
        operation["operationId"]
        for methods in document(version)["paths"].values()
        for operation in methods.values()
    )
    types = {name: _response_type(version, name) for name in operations}

    local = sorted(
        {t for t in types.values() if "." not in t and t != "Response"}
    )
    lines = [
        HEADER,
        "from collections.abc import Awaitable, Callable",
        "from typing import TypedDict",
        "",
        "from fastapi import Response",
        "",
    ]
    if any(t.startswith(f"{FIRST}.") for t in types.values()):
        lines.append(
            f"from app.types.handlers.{FIRST} import pydantic_gen as {FIRST}"
        )
    if local:
        lines.append(f"from .pydantic_gen import {', '.join(local)}")
    lines += ["", "", "class Operations(TypedDict):"]
    lines += [
        f"    {name}: Callable[..., Awaitable[{types[name]}]]"
        for name in operations
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    for version in VERSIONS:
        path = ROOT / "app" / "types" / "handlers" / version / "operations.py"
        path.write_text(render(version))
        print(f"{version}: {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
