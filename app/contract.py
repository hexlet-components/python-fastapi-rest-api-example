import json
from functools import lru_cache
from pathlib import Path
from typing import Any

CONTRACT_DIR = Path(__file__).resolve().parents[1] / "openapi"

# Версии контракта: адрес, с которого отдаётся версия, и её документ.
# Первая версия отдаётся с корня, вторая — с префиксом. Первая намеренно
# не уехала под /v1: адреса существующих клиентов переездом сломались бы,
# а версия по определению нужна для того, чтобы этого не делать.
VERSIONS = {"v1": "", "v2": "/v2"}


@lru_cache
def document(version: str) -> dict[str, Any]:
    """Документ версии контракта.

    Читается из файла, а не собирается по коду: контракт первичен, и
    приложение отдаёт клиенту ровно тот документ, из которого
    сгенерированы его же модели. Собранная по коду спека расходилась бы
    с контрактом ровно в тех местах, где расходится реализация, —
    и расхождение оставалось бы невидимым.
    """
    document = json.loads(
        (CONTRACT_DIR / f"openapi.{version}.json").read_text()
    )

    # Адрес версии проставляется в servers: пути внутри документа
    # префикса не знают — его навешивает приложение при подключении
    # роутеров. Без этой правки клиент, собранный по документу второй
    # версии, стучался бы в корень, то есть в первую.
    prefix = VERSIONS[version]
    if prefix:
        document["servers"] = [{"url": prefix, "description": version}]

    return document
