from app.db.models import User

# Публичная проекция пользователя: в строке лежит password_digest, и без
# явного перечисления колонок он уедет в выборку.
#
# Это второй слой защиты, а не единственный: ответ и так собирается по
# модели из контракта, поэтому поле вне контракта в тело не
# попадёт. Проекция нужна затем, чтобы секрет не покидал базу вовсе —
# если у маршрута однажды не окажется схемы ответа, сериализатор
# перестанет прикрывать.
#
# Проекций две, по одной на версию контракта: phone добавлен в User
# только со второй.
PUBLIC_USER_COLUMNS = (
    User.id,
    User.full_name,
    User.email,
)

PUBLIC_USER_COLUMNS_V2 = (*PUBLIC_USER_COLUMNS, User.phone)
